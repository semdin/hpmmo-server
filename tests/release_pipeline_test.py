def openssl(*args: str, stdin: bytes | None = None) -> subprocess.CompletedProcess:
    return subprocess.run([os.environ.get("HPMMO_OPENSSL", "openssl")] + list(args),
                          input=stdin, capture_output=True)


def find_bash() -> str | None:
    """A real POSIX bash. On Windows `bash` on PATH is the WSL launcher, which
    cannot run these scripts; deploy_rehearsal.py resolves it the same way."""
    override = os.environ.get("HPMMO_BASH")
    if override:
        return override if os.path.exists(override) else None
    if os.name == "nt":
        for candidate in (r"C:\Program Files\Git\usr\bin\bash.exe",
                          r"C:\Program Files\Git\bin\bash.exe",
                          r"C:\Program Files (x86)\Git\usr\bin\bash.exe"):
            if os.path.isfile(candidate):
                return candidate
        return None
    found = shutil.which("bash")
    return found if found else None


def looks_like_secret(path: str) -> str:
    """A stricter, value-based secret scan than `release_common.content_refusal`
    (which also matches the *patterns themselves* in the tool's own source)."""
    try:
        with open(path, "rb") as handle:
            data = handle.read(512 * 1024)
    except OSError:
        return ""
    text = data.decode("utf-8", "replace")
    if re.search(r"-----BEGIN [A-Z ]*PRIVATE KEY-----[ \t]*\r?\n[A-Za-z0-9+/=]{40,}", text):
        return "a PEM private key block"
    for pattern in (r"HPMMO_SERVICE_TOKEN=\S{8,}", r"HPMMO_DB_PASSWORD=\S{6,}",
                    r"PGPASSWORD=\S{6,}", r"DATABASE_URL=postgres(ql)?://",
                    r"postgres(ql)?://[^\s:@/]+:[^\s@/]+@"):
        if re.search(pattern, text):
            return "a credential value matching %s" % pattern
    return ""


def python_tool(script: str, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, script] + list(args), capture_output=True, text=True)


def temp_dir(prefix: str) -> str:
    return tempfile.mkdtemp(prefix=prefix, dir=_TEMP_ROOT)


def make_keypair(directory: str, name: str = "release") -> tuple[str, str]:
    key = os.path.join(directory, name + ".key.pem")
    pub = os.path.join(directory, name + ".pub.pem")
    result = openssl("genpkey", "-algorithm", "ed25519", "-out", key)
    assert result.returncode == 0, result.stderr
    result = openssl("pkey", "-in", key, "-pubout", "-out", pub)
    assert result.returncode == 0, result.stderr
    return key, pub


def spki_pin(public_key_path: str) -> str:
    """SPKI sha256 of a *public key* file (the manifest-side pin)."""
    result = openssl("pkey", "-pubin", "-in", public_key_path, "-pubout", "-outform", "DER")
    assert result.returncode == 0, result.stderr
    return hashlib.sha256(result.stdout).hexdigest()


def spki_pin_of_certificate(cert_path: str) -> str:
    """SPKI sha256 of a *certificate* (the TLS-side pin)."""
    public_key = openssl("x509", "-in", cert_path, "-noout", "-pubkey")
    assert public_key.returncode == 0, public_key.stderr
    result = openssl("pkey", "-pubin", "-outform", "DER", stdin=public_key.stdout)
    assert result.returncode == 0, result.stderr
    return hashlib.sha256(result.stdout).hexdigest()


def make_build_tree(parent: str) -> str:
    """A minimal but realistic build directory: an exported game payload and a
    launcher with its branding assets."""
    build = os.path.join(parent, "build")
    os.makedirs(os.path.join(build, "client"))
    os.makedirs(os.path.join(build, "launcher", "assets"))
    with open(os.path.join(build, "client", "hpmmo.exe"), "wb") as handle:
        handle.write(b"MZ" + b"\x00" * 512 + b"fake exported game executable\n")
    with open(os.path.join(build, "client", "hpmmo.pck"), "wb") as handle:
        handle.write(b"GDPC" + bytes(range(256)) * 16 + b"game payload\n")
    with open(os.path.join(build, "launcher", "hpmmo_launcher.exe"), "wb") as handle:
        handle.write(b"MZ" + b"\x00" * 256 + b"fake native launcher\n")
    with open(os.path.join(build, "launcher", "assets", "hpmmo_banner.jpg"), "wb") as handle:
        handle.write(b"\xff\xd8\xff\xe0fake jpeg\n")
    return build


def package(build: str, out: str) -> subprocess.CompletedProcess:
    return python_tool(PACKAGER, "--build-dir", build, "--client-version", CLIENT_VERSION,
                       "--content-version", CONTENT_VERSION, "--platform", PLATFORM, "--out", out)


def build_manifest(out: str, key: str, **overrides) -> subprocess.CompletedProcess:
    fields = {
        "--channel": "dev",
        "--client-version": CLIENT_VERSION,
        "--min-launcher-version": CLIENT_VERSION,
        "--protocol-version": "4",
        "--protocol-min": "4",
        "--protocol-max": "4",
        "--content-version": CONTENT_VERSION,
        "--server-version": "0.7.0",
        "--schema-version": "4",
        "--platform": PLATFORM,
        "--base-url": BASE_URL,
        "--published-at": PUBLISHED_AT,
        "--release-notes": "rehearsal manifest",
    }
    fields.update({k: str(v) for k, v in overrides.items()})
    args = ["--artifact", os.path.join(out, rc.artifact_name(CLIENT_VERSION, PLATFORM))]
    for name, value in fields.items():
        args += [name, value]
    return python_tool(MANIFEST_TOOL, *args, "--key", key, "--out", out)


def load_manifest(path: str) -> dict:
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def wait_for_https(port: int, context: ssl.SSLContext, timeout: float = 25.0) -> dict:
    deadline = time.time() + timeout
    last = None
    while time.time() < deadline:
        try:
            connection = http.client.HTTPSConnection("127.0.0.1", port, context=context, timeout=3)
            connection.request("GET", "/health")
            response = connection.getresponse()
            body = response.read()
            connection.close()
            if response.status == 200:
                return json.loads(body)
        except Exception as exc:  # noqa: BLE001 - the service may not be up yet
            last = exc
            time.sleep(0.2)
    raise RuntimeError("the status service never answered over HTTPS: %r" % (last,))


def https_get(port: int, path: str, context: ssl.SSLContext, method: str = "GET"):
    connection = http.client.HTTPSConnection("127.0.0.1", port, context=context, timeout=10)
    connection.request(method, path)
    response = connection.getresponse()
    body = response.read()
    return response.status, dict(response.getheaders()), body, connection


def fixture() -> dict:
    """Builds the shared rehearsal fixture exactly once: a key pair, a packaged
    artifact and a signed manifest, all under the temp root."""
    global _FIXTURE
    if _FIXTURE:
        return _FIXTURE
    root = temp_dir("fixture-")
    key, pub = make_keypair(root)
    build = make_build_tree(root)
    out = os.path.join(root, "dist")
    os.makedirs(out)

    result = package(build, out)
    check(result.returncode == 0, "[fixture] the packager builds an artifact from a clean build tree")
    if result.returncode != 0:
        note(result.stdout + result.stderr)
        return {}

    result = build_manifest(out, key)
    check(result.returncode == 0, "[fixture] the manifest is generated, signed and self-verified")
    if result.returncode != 0:
        note(result.stdout + result.stderr)
        return {}
    check("MANIFEST OK" in result.stdout, "[fixture] the tool proves its own output before anyone can publish it")

    _FIXTURE = {
        "root": root,
        "key": key,
        "pub": pub,
        "build": build,
        "out": out,
        "artifact": os.path.join(out, rc.artifact_name(CLIENT_VERSION, PLATFORM)),
        "manifest": os.path.join(out, "manifest.json"),
    }
    return _FIXTURE


