#!/usr/bin/env python3
"""Release pipeline client release pipeline rehearsal.

Drives the REAL release tooling against a fully synthetic environment in a temp
directory:

  * `client/tools/release/package_client.py` packages a fake build tree,
  * `client/tools/release/gen_manifest.py` signs the manifest with a throwaway
    Ed25519 key generated by the OpenSSL CLI,
  * `server/deploy/tls/make_cert.sh` generates the self-signed release
    certificate and the SPKI pin,
  * `server/deploy/hpmmo_status.py` serves the status document and the release
    root over HTTPS with that certificate, on a loopback port.

Nothing here touches the live box, the real keys, or the repository: every
artifact, key, certificate, channel pointer and process lives under a temp root
that is removed at the end.

Rehearsed exit checks ("Exit checks" + the release contract):

  1. deterministic packaging: the same build tree produces the same zip bytes
  2. deterministic manifest: the same inputs and a pinned --published-at
     produce the same manifest bytes, and the same signature
  3. the signature verifies over the exact manifest bytes; the .sig file is one
     line of base64 holding a raw 64-byte signature; the key id travels in the
     sidecar and equals the pinned public key's SPKI sha256
  4. a tampered manifest fails verification; the right manifest under a wrong
     key (or an unexpected key id) fails verification
  5. a tampered artifact fails its recorded hash
  6. the package contains no user data, no editor cache and no secret - and the
     packager refuses a build tree that does (by path and by content)
  7. the version fields gate correctly: a server-only bump (new server_version /
     schema_version against an identical client artifact) requires NO client
     download, while a client bump, a raised protocol floor, a raised launcher
     minimum and a content mismatch behave as documented
  8. HTTPS: the pinned certificate is served, /releases/ serves the manifest
     (whose signature verifies over the served bytes) and the artifact, HEAD
     reports the size, traversal and dotfile requests are refused, and a public
     bind without TLS is refused
  9. the contracted files exist, the workflow carries the required controls, and
     no key material is committed beside the tooling

Usage:
  python server/tests/release_pipeline_test.py [--case NAME] [--keep] [--verbose]

Set HPMMO_CLIENT_REPO to point at another checkout of the client repository,
HPMMO_OPENSSL to use a different openssl binary.

Prints one PASS/FAIL line per check and finishes with
    RELEASE RESULT: N checks, M failures
Exit code is 0 when there are no failures (1 otherwise, 2 when the tooling
cannot run at all).
"""

