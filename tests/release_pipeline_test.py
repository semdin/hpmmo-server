def check(condition, message: str) -> bool:
    global checks
    checks += 1
    if condition:
        print("PASS: " + message)
        return True
    failures.append(message)
    print("FAIL: " + message)
    return False


def note(message: str) -> None:
    if VERBOSE:
        print("      " + message)


def say(message: str) -> None:
    print("\n--- %s ---" % message)


